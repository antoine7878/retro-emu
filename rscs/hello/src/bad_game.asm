	ld a, [de]
	ld [hli], a
	inc de
	dec bc
	ld a, b
	or a, c
	jr nz, CopyTilemap

	ld a, LCDC_ON | LCDC_BG_ON
	ld [rLCDC], a

	ld a, %11100100
	ld [rBGP], a

Done:
	jr Done


