SECTION "Header", ROM0[$100]

	jp EntryPoint

	ds $150 - @, 0

EntryPoint:
	ld a, 0
	ld [rNR52], a

WaitVBlank:
	ld a, [rLY]
	cp 144
	jr c, WaitVBlank

	ld a, 0
	ld [rLCDC], a

	ld de, Tiles
	ld hl, $9000
	ld bc, Tiles.End - Tiles

CopyTiles:
	ld a, [de]
	ld [hli], a
	inc de
	dec bc
	ld a, b
	or a, c
	jr nz, CopyTiles

	ld de, Tilemap
	ld hl, $9800
	ld bc, Tilemap.End - Tilemap

